function pick() {
  try {
    const saved = typeof window !== 'undefined'
      ? (window.localStorage?.getItem('broco-lang') ?? window.localStorage?.getItem('cc-bro-lang'))
      : null
    if (saved && dict[saved]) return saved
  } catch {}
  return (typeof navigator !== 'undefined' ? (navigator.language || 'en') : 'en').toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export const lang = $state({ current: pick() })

export function t(key) {
  return dict[lang.current][key] ?? dict.en[key] ?? key
}

export function setLang(code) {
  lang.current = code
  try {
    if (typeof window !== 'undefined') window.localStorage?.setItem('broco-lang', code)
  } catch {}
}

export function tf(key, vars) {
  return t(key).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '')
}

export function translateActivity(text) {
  if (!text || lang.current !== 'zh') return text || ''
  return zhActivity[text] ?? text
}

export function loginStatusLabel(installed, status) {
  if (!installed) return t('statusNotInstalled')
  if (status === 'ready') return t('statusReady')
  if (status === 'signed-out') return t('statusSignedOut')
  if (status === 'expired') return t('statusExpired')
  if (status === 'not-required') return t('statusNotRequired')
  return t('statusUnknown')
}
